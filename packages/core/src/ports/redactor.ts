// ports/redactor.ts
// SK 共享内核：Redactor 端口——敏感信息脱敏抽象（对齐 architecture.md §4.3、prd.md FR-3、AC-3/AC-4）。
// 零框架 import。本文件只定义端口接口，不含任何适配器实现。
//
// 语义契约：
//   - 内建规则集须覆盖以下敏感样式（FR-3.2）：
//       · API Key（如 sk- 前缀的密钥）
//       · Bearer token（Authorization 头中的令牌）
//       · 绝对路径中的用户名段（如 /home/<user>/ 或 C:\Users\<user>\）
//       · 邮箱地址
//       · 常见密钥前缀（如各类云厂商 / 服务的 token 前缀）
//   - 脱敏用占位符 ***REDACTED*** 替换命中片段，保留可读结构（FR-3.3），
//     不整体抹除，便于日志仍具可读性与可诊断性。
//   - 纯函数、无副作用：返回脱敏后的新副本，绝不修改传入对象（AC-4/FR-3.1）。
//   - 上层（领域/应用逻辑）经此端口对外发数据前脱敏，保证核心包纯净、可测试。
//
// 说明：具体正则规则集与纯函数默认实现属适配器层（如 apps/api 的 RegexRedactor），
//       本文件仅定义端口契约，不含实现。

/**
 * 脱敏端口：对字符串与结构化对象做敏感信息脱敏。
 * 生产实现内建规则集覆盖 API Key / Bearer token / 绝对路径用户名段 / 邮箱 / 常见密钥前缀（FR-3.2），
 * 命中片段用占位符 ***REDACTED*** 替换并保留可读结构（FR-3.3）。
 * 所有方法均为纯函数、无副作用：返回脱敏后的新副本，不修改原输入（AC-4/FR-3.1）。
 */
export interface Redactor {
  /** 对字符串脱敏，返回脱敏后新串。 */
  redactString(input: string): string;
  /** 对结构化对象深度脱敏，返回脱敏后新副本，不修改原对象。 */
  redact<T>(input: T): T;
}
